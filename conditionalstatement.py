# Conditional Statement (IF, ELIF,ELSE)

# Example 1: Simple IF statement
age = 33
if age >= 18:
    print("YoU are eligible to get an ID")
else:
    print("You are not eligible to get an ID")


# Example : IF-ELIF-ELSE statement
marks = 69

if marks >= 80:
    print("Grade: A")
elif marks >= 60:
    print("Grade: B")
elif marks >= 50:
    print("Grade: C")   
else:
    print("Grade: D")


